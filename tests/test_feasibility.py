"""check_servicing_bounds() flags scenarios no solution can satisfy, whichever way departures are
matched to arrivals. The seed-300 one-train scenario of the servicing sweep (three VIRM-4 units with
a 900 s Wasmachine task each, in the yard from 480 s to 3140 s, one washing place) was generated by
the generator at 2.4.0 and cannot be solved: washing alone takes 2700 s of the 2660 s."""

from feasibility import check_servicing_bounds, facility_capacities


def location(wash_capacity=1):
    return {
        "facilities": [
            {
                "id": 72,
                "type": "Reinigingsperron",
                "taskTypes": [{"other": "Reinigingsperron"}],
                "simultaneousUsageCount": 2,
            },
            {
                "id": 73,
                "type": "Wasmachine",
                "taskTypes": [{"other": "Wasmachine"}],
                "simultaneousUsageCount": wash_capacity,
            },
        ]
    }


def unit(*tasks):
    return {
        "typePrefix": "VIRM",
        "carriages": 4,
        "tasks": [{"type": {"other": name}, "duration": d} for name, d in tasks],
    }


def train_in(train_id, arrival, *units):
    return {"id": train_id, "arrival": arrival, "departure": arrival, "members": list(units)}


def train_out(train_id, departure):
    return {"id": train_id, "arrival": departure, "departure": departure, "trainUnits": []}


def sweep_scenario():
    washing = ("Wasmachine", 900)
    return {"in": [train_in(0, 480, unit(washing), unit(washing), unit(washing))], "out": [train_out(1, 3140)]}


class TestSingleTrain:
    def test_flags_the_seed_300_scenario(self):
        violations = check_servicing_bounds(sweep_scenario(), location())

        assert {v.facility_type for v in violations} == {"Wasmachine"}
        assert {v.train_id for v in violations} == {None, 0}  # the scenario bound and the train bound
        assert all(v.required == 2700 and v.available == 2660 for v in violations)

    def test_passes_when_the_stay_is_long_enough(self):
        scenario = sweep_scenario()
        scenario["out"] = [train_out(1, 3180)]

        assert check_servicing_bounds(scenario, location()) == []

    def test_a_second_washing_place_halves_the_demand(self):
        assert check_servicing_bounds(sweep_scenario(), location(wash_capacity=2)) == []

    def test_travel_allowance_counts_only_when_asked(self):
        scenario = sweep_scenario()
        scenario["out"] = [train_out(1, 3180)]

        assert check_servicing_bounds(scenario, location(), travel_allowance=0) == []
        assert [v.train_id for v in check_servicing_bounds(scenario, location(), travel_allowance=100)] == [0]

    def test_tasks_without_a_facility_and_unserviced_units_are_ignored(self):
        scenario = {"in": [train_in(0, 0, unit(("Unknown", 99999)), unit())], "out": [train_out(1, 100)]}

        assert check_servicing_bounds(scenario, location()) == []


class TestSeveralTrains:
    def test_total_demand_of_all_trains_must_fit_the_scenario(self):
        washing = ("Wasmachine", 900)
        scenario = {
            "in": [train_in(0, 0, unit(washing), unit(washing)), train_in(1, 480, unit(washing), unit(washing))],
            "out": [train_out(2, 3000), train_out(3, 3500)],
        }

        violations = check_servicing_bounds(scenario, location())

        assert [(v.train_id, v.required, v.available) for v in violations] == [(None, 3600, 3500)]

    def test_no_per_train_bound_because_the_matching_is_unknown(self):
        # Train 0 alone needs 2700 s and the first departure is at 1000 s, but its units may
        # leave with the second train, so only the scenario-wide bound applies.
        washing = ("Wasmachine", 900)
        scenario = {
            "in": [train_in(0, 0, unit(washing), unit(washing), unit(washing)), train_in(1, 480, unit())],
            "out": [train_out(2, 1000), train_out(3, 3000)],
        }

        assert check_servicing_bounds(scenario, location()) == []

    def test_window_starts_at_the_first_arrival_that_needs_the_facility(self):
        # Train 0 needs nothing, so the early arrival does not widen the washing window.
        washing = ("Wasmachine", 900)
        scenario = {
            "in": [train_in(0, 0, unit()), train_in(1, 2000, unit(washing), unit(washing))],
            "out": [train_out(2, 3000), train_out(3, 3500)],
        }

        assert [v.required for v in check_servicing_bounds(scenario, location())] == [1800]


def test_facility_capacities_sum_over_facilities_of_a_type():
    loc = location()
    loc["facilities"].append(
        {"id": 99, "type": "Wasmachine", "taskTypes": [{"other": "Wasmachine"}], "simultaneousUsageCount": 2}
    )

    assert facility_capacities(loc) == {"Reinigingsperron": 2, "Wasmachine": 3}
